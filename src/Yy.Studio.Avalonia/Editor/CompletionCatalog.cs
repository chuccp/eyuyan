    public static bool IsBuiltin(string text) => BuiltinNames.Contains(text);

    public static BuiltinDoc? FindBuiltin(string name) =>
        Builtins.FirstOrDefault(item => string.Equals(item.Name, name, StringComparison.Ordinal));

    public static (string Text, string Description)? FindKeyword(string word)
    {
        var match = Completions.FirstOrDefault(item =>
            string.Equals(item.Text, word, StringComparison.Ordinal));
        return match.Text is null ? null : match;
    }

    public static string DescribeCallable(string name)
    {
        var builtin = FindBuiltin(name);
        if (builtin is not null)
        {
            return builtin.Signature + "\n\n" + builtin.Description;
        }

        var keyword = FindKeyword(name);
        return keyword is { } value
            ? value.Text + "\n\n" + value.Description
            : $"未找到“{name}”的帮助。";
    }
